# 답:

import pandas as pd

# 진통제 데이터를 정의
df = pd.DataFrame({
    "진통제": [4, 4, 3, 4, 1, 4, 4, 1, 4, 4, 2, 1, 4, 2, 3, 2, 2, 4, 4, 4]
})

# 관찰된 값 (각 부작용 발생 횟수)

# 1. 두통: 10%
# 2. 약간의 메스꺼움: 5%
# 3. 어지러움: 15%
# 4. 무증상: 70%

observe = df.value_counts().sort_index()
observe

expect = [0.1 * 20, 0.05 * 20, 0.15 * 20, 0.7 * 20]
expect

from scipy.stats import chisquare
stats, p_value = chisquare(observe, expect)
print(stats)

# 1-3. 위의 p-값을 구하시오.
print(p_value)