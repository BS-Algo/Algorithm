# 작업 시간이 결측치인 경우, 해당하는 작업 공정의 작업 시간 평균값으로 결측치를 대체합니다.

# 결측치를 모두 대체한 후, 다음 값을 구합니다:

# 1.작업 시간중 가장 긴 값
# 2.작업 시간이 가장 긴 값인 기계 수

# 작업 시간이 가장 긴 값 + 작업 시간이 가장 긴 값인 기계 수 값을 출력하세요.

# 데이터 불러오기
import pandas as pd
df = pd.read_csv("factory_data.csv")
# df.isnull().sum()
df['작업공정'] = df['작업공정'].fillna(df['작업공정'].mode()[0])
# df.isnull().sum()
df['작업시간'] = df['작업시간'].fillna(df['작업시간'].mean())
# df.isnull().sum()
a = df['작업시간'].max()
b = (df['작업시간'] == a).sum()
ans = a + b
print(ans)